const bugganeContainers = document.getElementById("buggane-containers");
let correct = 0;

function setCorrect() {
    correct = Math.ceil(Math.random() * bugganeyn.size);
    const correctXY = bugganeyn.get(correct).position;
};

function showBuggane (event) {
    document.body.style.overflow = "hidden";
    const bugganeClicked = bugganeyn.get(parseInt(event.target.id.match(/[0-9]/g).join("")) + 1);
    coverContainer.style.visibility = "visible";
    bugganeCover = coverContainer.firstElementChild;
    bugganeCover.style.visibility = "visible";
    const stdVector = bugganeClicked.position.map(v => Math.ceil(v / 100) * 250);
    bugganeCover.firstElementChild.style.backgroundPosition = `-${stdVector[0]}px -${stdVector[1]}px`;
    bugganeCover.lastElementChild.textContent = bugganeClicked.ennym;
};

function makeGrid () {
    const gridSlots = [];
    const gridNumbers = [];
    const gridOrder = [];
    let cellCount = 0;
    const cellSize = window.matchMedia('(min-width: 600px)').matches ? 100 : 75;
    for (let i = 0; i < 4; i++) {
        for (let j = 0; j < 4; j++) {
            gridSlots.push([j * cellSize, i * cellSize]);
            gridNumbers.push(cellCount);
            cellCount++;
        };
    };
    for (let i = 0; i < 16; i++) {
        const r = Math.floor(Math.random() * gridNumbers.length);
        gridOrder.push(...gridNumbers.splice(r, 1));
    };
    cellCount = 0;
    for (let i = 0; i < 4; i++) {
        for (let j = 0; j < 4; j++) {
            const cellBkgr = document.createElement("div");
                cellBkgr.id = `cell-bkgr-${gridOrder[cellCount]}`;
                cellBkgr.classList.add("cell-bkgr");
                cellBkgr.style.gridColumn = i + 1;
                cellBkgr.style.gridRow = j + 1;
                cellBkgr.style.backgroundPosition = `${i * 100}px ${j * 100}px`;
            const cellCover = document.createElement("div");
                cellCover.id = `cell-cover-${gridOrder[cellCount]}`;
                cellCover.classList.add("cell-cover");
                cellCover.style.gridColumn = i + 1;
                cellCover.style.gridRow = j + 1;
            const cellFloor = document.createElement("div");
                cellFloor.id = `cell-floor-${gridOrder[cellCount]}`;
                cellFloor.classList.add("cell-floor");
                cellFloor.style.gridColumn = i + 1;
                cellFloor.style.gridRow = j + 1;
            const cell = document.createElement("div");
                cell.style.gridColumn = i + 1;
                cell.style.gridRow = j + 1;
                cell.id = `buggane-container-${gridOrder[cellCount]}`;
                cell.classList.add("buggane-container");
            const bugganeynObj = bugganeyn.get(gridOrder[cellCount] + 1);
                bugganeynObj.position = [gridSlots[gridOrder[cellCount]][0], gridSlots[gridOrder[cellCount]][1]];
                const cellBuggane = document.createElement("div");
                    cellBuggane.id = `buggane-${gridOrder[cellCount]}`;
                    cellBuggane.classList.add("buggane");
                    cellBuggane.style.backgroundPosition = `-${bugganeyn.get(gridOrder[cellCount] + 1).position[0]}px -${bugganeyn.get(gridOrder[cellCount] + 1).position[1]}px`;
                const cellName = document.createElement("div");
                    cellName.classList.add("buggane-name");
                    cellName.textContent = bugganeyn.get(gridOrder[cellCount] + 1)["ennym"];
                cell.append(cellBuggane, cellName);
                cell.addEventListener("click", showBuggane);
            bugganeContainers.append(cellBkgr, cellCover, cellFloor, cell);
            cellCount++;
        };
    };
    setCorrect();
};
makeGrid();
